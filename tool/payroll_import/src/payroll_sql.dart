String _uuid(String id) => "'$id'::uuid";

String _userOf(
  String? profileId,
  String businessId,
  String Function(String) userId,
) => profileId == null
    ? 'NULL'
    : '(SELECT u.id FROM public.users u WHERE u.id = ${_uuid(userId(profileId))} '
          'AND u.business_id = ${_uuid(businessId)})';

String _list(Iterable<String> values) => values.map(sqlText).join(', ');

/// One transaction, insert-only. Every row has a fixed id and a legacy id, so
/// `ON CONFLICT DO NOTHING` makes a second run insert nothing. Entries and
/// statements are frozen in the cloud, so nothing here ever updates.
String buildPayrollImportSql({
  required PayrollPlan plan,
  required String Function(String profileId) userId,
}) {
  final biz = plan.businessId;
  final out = StringBuffer()
    ..writeln(
      '-- Generated by tool/payroll_import (#672). Contains real pay data.',
    )
    ..writeln(
      '-- Do not commit. Run with: psql -v ON_ERROR_STOP=1 -f import.sql',
    )
    ..writeln()
    ..writeln('BEGIN;')
    ..writeln()
    ..writeln('-- Guards: stop before writing anything on the wrong database.')
    ..writeln(r'DO $$')
    ..writeln('BEGIN')
    ..writeln(
      '  IF NOT EXISTS (SELECT 1 FROM public.businesses WHERE id = ${_uuid(biz)}) THEN',
    )
    ..writeln("    RAISE EXCEPTION 'business $biz is not on this database';")
    ..writeln('  END IF;')
    ..writeln('  IF EXISTS (')
    ..writeln(
      '    SELECT 1 FROM (VALUES ${plan.storeIds.map((s) => '(${_uuid(s)})').join(', ')}) AS v(id)',
    )
    ..writeln('    WHERE NOT EXISTS (SELECT 1 FROM public.stores s')
    ..writeln(
      '                      WHERE s.id = v.id AND s.business_id = ${_uuid(biz)})',
    )
    ..writeln('  ) THEN')
    ..writeln(
      "    RAISE EXCEPTION 'a worker store is not in this business (run the #623 import first)';",
    )
    ..writeln('  END IF;')
    ..writeln('  IF NOT EXISTS (')
    ..writeln('    SELECT 1 FROM information_schema.columns')
    ..writeln(
      "    WHERE table_schema = 'public' AND table_name = 'payroll_entries'",
    )
    ..writeln("      AND column_name = 'status'")
    ..writeln('  ) THEN')
    ..writeln(
      "    RAISE EXCEPTION 'payroll schema is behind: apply 0243-0246 first';",
    )
    ..writeln('  END IF;')
    ..writeln('  IF NOT EXISTS (')
    ..writeln('    SELECT 1 FROM pg_constraint')
    ..writeln("    WHERE conrelid = 'public.staff_pay_totals'::regclass")
    ..writeln("      AND pg_get_constraintdef(oid) ILIKE '%loans_repaid%'")
    ..writeln('  ) THEN')
    ..writeln(
      "    RAISE EXCEPTION 'staff_pay_totals kinds are behind: apply 0246 first';",
    )
    ..writeln('  END IF;')
    ..writeln(
      '  -- A worker already added by hand would be paid twice in reports.',
    )
    ..writeln('  IF EXISTS (')
    ..writeln('    SELECT 1 FROM public.payroll_workers w')
    ..writeln('    WHERE w.business_id = ${_uuid(biz)} AND w.legacy_id IS NULL')
    ..writeln(
      '      AND lower(trim(w.name)) IN (${_list(plan.workers.map((w) => w.name.trim().toLowerCase()))})',
    )
    ..writeln('  ) THEN')
    ..writeln(
      "    RAISE EXCEPTION 'a worker with an imported name was already added by hand';",
    )
    ..writeln('  END IF;')
    ..writeln('END')
    ..writeln(r'$$;')
    ..writeln();

  final workers = TargetTable('payroll_workers', [
    'id', 'business_id', 'store_id', 'name', 'monthly_salary_kobo', //
    'daily_allowance_kobo', 'legacy_id', 'created_at',
  ]);
  for (final w in plan.workers) {
    workers.add({
      'id': _uuid(w.id),
      'business_id': _uuid(biz),
      'store_id': _uuid(w.storeId),
      'name': sqlText(w.name),
      'monthly_salary_kobo': sqlInt(w.monthlySalaryKobo),
      // Daily allowances are never backdated: set in the app, from today.
      'daily_allowance_kobo': '0',
      'legacy_id': sqlText(w.legacyId),
      'created_at': sqlTime(w.createdAt),
    });
  }

  const entryColumns = [
    'id', 'business_id', 'worker_id', 'store_id', 'type', 'amount_kobo', //
    'entry_date', 'salary_month', 'payment_method', 'note', //
    'corrects_entry_id', 'recorded_by', 'status', 'approved_by', //
    'approved_at', 'legacy_id', 'created_at',
  ];
  final originals = TargetTable('payroll_entries', entryColumns);
  final corrections = TargetTable('payroll_entries', entryColumns);
  for (final e in plan.entries) {
    final by = _userOf(e.recordedByProfileId, biz, userId);
    (e.correctsEntryId == null ? originals : corrections).add({
      'id': _uuid(e.id),
      'business_id': _uuid(biz),
      'worker_id': _uuid(e.workerId),
      'store_id': _uuid(e.storeId),
      'type': sqlText(e.type),
      'amount_kobo': sqlInt(e.amountKobo),
      'entry_date': "'${e.entryDate}'::date",
      'salary_month': sqlText(e.salaryMonth),
      'payment_method': sqlText(e.paymentMethod),
      'note': sqlText(e.note),
      'corrects_entry_id': e.correctsEntryId == null
          ? 'NULL'
          : _uuid(e.correctsEntryId!),
      'recorded_by': by,
      'status': "'approved'",
      'approved_by': by,
      'approved_at': sqlTime(e.createdAt),
      'legacy_id': sqlText(e.legacyId),
      'created_at': sqlTime(e.createdAt),
    });
  }

  final statements = TargetTable('payroll_statements', [
    'id', 'business_id', 'worker_id', 'store_id', 'salary_month', //
    'salary_kobo', 'allowances_kobo', 'bonuses_kobo', 'advances_kobo', //
    'loan_repaid_kobo', 'cash_paid_kobo', 'total_pay_kobo', //
    'salary_entry_id', 'worker_signature_png', 'payer_signature_png', //
    'signed_by', 'signed_at', 'legacy_id', 'created_at',
  ]);
  for (final s in plan.statements) {
    statements.add({
      'id': _uuid(s.id),
      'business_id': _uuid(biz),
      'worker_id': _uuid(s.workerId),
      'store_id': _uuid(s.storeId),
      'salary_month': sqlText(s.salaryMonth),
      'salary_kobo': sqlInt(s.salaryKobo),
      'allowances_kobo': sqlInt(s.allowancesKobo),
      'bonuses_kobo': sqlInt(s.bonusesKobo),
      'advances_kobo': sqlInt(s.advancesKobo),
      'loan_repaid_kobo': sqlInt(s.loanRepaidKobo),
      'cash_paid_kobo': sqlInt(s.cashPaidKobo),
      'total_pay_kobo': sqlInt(s.totalPayKobo),
      'salary_entry_id': _uuid(s.salaryEntryId),
      'worker_signature_png': sqlText(s.workerSignaturePng),
      'payer_signature_png': sqlText(s.payerSignaturePng),
      'signed_by': _userOf(s.signedByProfileId, biz, userId),
      'signed_at': sqlTime(s.signedAt),
      'legacy_id': sqlText(s.legacyId),
      'created_at': sqlTime(s.createdAt),
    });
  }

  // The combined lines the Payroll phones would derive after their next pull
  // (same ids and figures), so reports on every phone are right at once. A
  // line a phone already wrote is left for that phone's refresh to converge.
  final totals = TargetTable('staff_pay_totals', [
    'id', 'business_id', 'store_id', 'kind', 'total_date', 'amount_kobo', //
    'cash_kobo',
  ]);
  for (final t in plan.payTotals) {
    totals.add({
      'id': _uuid(t.id),
      'business_id': _uuid(biz),
      'store_id': _uuid(t.storeId),
      'kind': sqlText(t.kind),
      'total_date': "'${t.totalDate}'::date",
      'amount_kobo': sqlInt(t.amountKobo),
      'cash_kobo': sqlInt(t.cashKobo),
    });
  }

  for (final table in [workers, originals, corrections, statements, totals]) {
    if (table.rows.isEmpty) continue;
    table.writeInserts(out);
    out.writeln();
  }

  out
    ..writeln('-- Every planned row must now be there, or nothing is kept.')
    ..writeln(r'DO $$')
    ..writeln('BEGIN')
    ..writeln(
      _expectCount('payroll_workers', biz, plan.workers.map((w) => w.legacyId)),
    )
    ..writeln(
      _expectCount('payroll_entries', biz, plan.entries.map((e) => e.legacyId)),
    )
    ..writeln(
      _expectCount(
        'payroll_statements',
        biz,
        plan.statements.map((s) => s.legacyId),
      ),
    )
    ..writeln('END')
    ..writeln(r'$$;')
    ..writeln()
    ..writeln('COMMIT;');
  return out.toString();
}

String _expectCount(String table, String biz, Iterable<String> legacyIds) {
  final ids = legacyIds.toList();
  if (ids.isEmpty) return '  NULL;';
  return '  IF (SELECT count(*) FROM public.$table WHERE business_id = ${_uuid(biz)}\n'
      '      AND legacy_id IN (${_list(ids)})) <> ${ids.length} THEN\n'
      "    RAISE EXCEPTION '$table: not every planned row landed';\n"
      '  END IF;';
}

/// Read-only. One PASS/FAIL row per check against the private plan's figures,
/// then an overall verdict.
String buildPayrollChecksSql({
  required PayrollPlan plan,
  required PayrollExpected expected,
}) {
  final biz = _uuid(plan.businessId);
  final workerLegacy = _list(plan.workers.map((w) => w.legacyId));
  final entryLegacy = _list(plan.entries.map((e) => e.legacyId));
  final statementLegacy = _list(plan.statements.map((s) => s.legacyId));
  final workerIds = plan.workers.map((w) => _uuid(w.id)).join(', ');
  final checks = <(String, String, String)>[];
  void check(String name, String expectedSql, String actualSql) =>
      checks.add((name, expectedSql, actualSql));

  String workersWhere = 'business_id = $biz AND legacy_id IN ($workerLegacy)';
  String entriesWhere = 'business_id = $biz AND legacy_id IN ($entryLegacy)';
  String statementsWhere = statementLegacy.isEmpty
      ? 'false'
      : 'business_id = $biz AND legacy_id IN ($statementLegacy)';
  const owed =
      "COALESCE(SUM(CASE type WHEN 'loan_given' THEN amount_kobo "
      "WHEN 'loan_repaid' THEN -amount_kobo ELSE 0 END), 0)";

  check(
    'workers',
    '${expected.workers}',
    'SELECT count(*) FROM public.payroll_workers WHERE $workersWhere',
  );
  check(
    'worker names, stores and salaries as planned',
    '${plan.workers.length}',
    'SELECT count(*) FROM public.payroll_workers w JOIN (VALUES '
        '${plan.workers.map((w) => '(${sqlText(w.legacyId)}, ${sqlText(w.name)}, ${_uuid(w.storeId)}, ${w.monthlySalaryKobo}::bigint)').join(', ')}'
        ') AS p(legacy_id, name, store_id, salary) ON p.legacy_id = w.legacy_id '
        'AND p.name = w.name AND p.store_id = w.store_id '
        'AND p.salary = w.monthly_salary_kobo AND w.daily_allowance_kobo = 0 '
        'WHERE w.business_id = $biz',
  );
  check(
    'statements',
    '${expected.statements}',
    'SELECT count(*) FROM public.payroll_statements WHERE $statementsWhere',
  );
  check(
    'statements signed by worker and payer',
    '${expected.statements}',
    'SELECT count(*) FROM public.payroll_statements WHERE $statementsWhere '
        "AND COALESCE(worker_signature_png, '') <> '' "
        "AND COALESCE(payer_signature_png, '') <> ''",
  );
  check(
    'statements point at their salary payment',
    '${expected.statements}',
    'SELECT count(*) FROM public.payroll_statements s JOIN public.payroll_entries e '
        "ON e.id = s.salary_entry_id AND e.type = 'salary_payment' "
        'AND e.salary_month = s.salary_month AND e.amount_kobo = s.salary_kobo '
        'WHERE s.business_id = $biz AND s.legacy_id IN ($statementLegacy)',
  );
  check(
    'salary cost (kobo)',
    '${expected.salaryKobo}',
    "SELECT COALESCE(SUM(amount_kobo), 0) FROM public.payroll_entries WHERE $entriesWhere AND type = 'salary_payment'",
  );
  check(
    'cash out on payday (kobo)',
    '${expected.cashOutKobo}',
    'SELECT COALESCE(SUM(cash_paid_kobo), 0) FROM public.payroll_statements WHERE $statementsWhere',
  );
  check(
    'cash out = salary - advances - loan repaid',
    '0',
    'SELECT count(*) FROM public.payroll_statements WHERE $statementsWhere '
        'AND cash_paid_kobo <> salary_kobo - advances_kobo - loan_repaid_kobo',
  );
  check(
    'salary months as planned',
    '${plan.statements.length}',
    'SELECT count(*) FROM public.payroll_statements s JOIN (VALUES '
        '${plan.statements.map((s) => '(${sqlText(s.legacyId)}, ${sqlText(s.salaryMonth)})').join(', ')}'
        ') AS p(legacy_id, month) ON p.legacy_id = s.legacy_id AND p.month = s.salary_month '
        'WHERE s.business_id = $biz',
  );
  check(
    'loan entries',
    '${expected.loanEntries}',
    "SELECT count(*) FROM public.payroll_entries WHERE $entriesWhere AND type IN ('loan_given', 'loan_repaid')",
  );
  check(
    'loans still owed (kobo)',
    '${expected.totalLoansOwedKobo}',
    'SELECT $owed FROM public.payroll_entries WHERE $entriesWhere',
  );
  for (final w in plan.workers) {
    check(
      'loan owed: ${w.name}',
      '${expected.loansOwedKobo[w.legacyId] ?? 0}',
      'SELECT $owed FROM public.payroll_entries WHERE $entriesWhere '
          'AND worker_id = ${_uuid(w.id)}',
    );
  }
  check(
    'payday loan deductions kept out of till cash',
    '0',
    "SELECT count(*) FROM public.payroll_entries WHERE $entriesWhere AND type = 'loan_repaid' "
        "AND note LIKE 'Taken from % salary' AND payment_method <> 'other'",
  );
  check(
    'cancelled history nets to zero (advances)',
    '0',
    "SELECT COALESCE(SUM(amount_kobo), 0) FROM public.payroll_entries WHERE $entriesWhere AND type = 'advance'",
  );
  check(
    'every planned entry landed',
    '${plan.entries.length}',
    'SELECT count(*) FROM public.payroll_entries WHERE $entriesWhere',
  );
  check(
    'no daily allowances imported',
    '0',
    "SELECT count(*) FROM public.payroll_entries WHERE worker_id IN ($workerIds) AND type = 'allowance'",
  );
  check(
    'combined pay lines as the app derives them',
    '${plan.payTotals.length}',
    plan.payTotals.isEmpty
        ? 'SELECT 0'
        : 'SELECT count(*) FROM public.staff_pay_totals t JOIN (VALUES '
              '${plan.payTotals.map((t) => '(${_uuid(t.id)}, ${t.amountKobo}::bigint, ${t.cashKobo}::bigint)').join(', ')}'
              ') AS p(id, amount, cash) ON p.id = t.id AND p.amount = t.amount_kobo '
              'AND p.cash = t.cash_kobo WHERE t.business_id = $biz',
  );

  final out = StringBuffer()
    ..writeln(
      '-- Generated by tool/payroll_import (#672). Read-only. Real pay data.',
    )
    ..writeln('WITH c(n, name, expected, actual) AS (');
  for (var i = 0; i < checks.length; i++) {
    final (name, exp, act) = checks[i];
    out.writeln(
      '  ${i == 0 ? '' : 'UNION ALL '}SELECT ${i + 1}, ${sqlText(name)}, '
      '($exp)::bigint, ($act)::bigint',
    );
  }
  out
    ..writeln(')')
    ..writeln(
      "SELECT n, name, expected, actual, CASE WHEN expected = actual THEN 'PASS' ELSE 'FAIL' END AS result FROM c",
    )
    ..writeln('UNION ALL')
    ..writeln(
      "SELECT ${checks.length + 1}, 'overall', count(*) FILTER (WHERE expected = actual), count(*), "
      "CASE WHEN bool_and(expected = actual) THEN 'PASS' ELSE 'FAIL' END FROM c",
    )
    ..writeln('ORDER BY 1;');
  return out.toString();
}

/// What will be written and what stays behind, for review before the run.
String buildPayrollReport(PayrollPlan plan) {
  final out = StringBuffer()
    ..writeln('# Payroll import (#672). Real pay data: do not commit.')
    ..writeln()
    ..writeln('Business: ${plan.businessId}')
    ..writeln()
    ..writeln('## Workers (${plan.workers.length})')
    ..writeln();
  for (final w in plan.workers) {
    out.writeln(
      '- ${w.name}: salary ${w.monthlySalaryKobo} kobo, store ${w.storeId}',
    );
  }
  out
    ..writeln()
    ..writeln('## Entries (${plan.entries.length})')
    ..writeln();
  final names = {for (final w in plan.workers) w.id: w.name};
  for (final e in plan.entries) {
    out.writeln(
      '- ${e.entryDate} (${e.dateSource}) ${names[e.workerId]}: ${e.type} '
      '${e.amountKobo} kobo, ${e.paymentMethod}'
      '${e.salaryMonth == null ? '' : ', month ${e.salaryMonth}'}'
      '${e.correctsEntryId == null ? '' : ', corrects ${e.correctsEntryId}'}'
      '${e.note == null ? '' : ', note "${e.note}"'}',
    );
  }
  out
    ..writeln()
    ..writeln('## Statements (${plan.statements.length})')
    ..writeln();
  for (final s in plan.statements) {
    out.writeln(
      '- ${names[s.workerId]} ${s.salaryMonth}: salary ${s.salaryKobo}, '
      'advances ${s.advancesKobo}, loan repaid ${s.loanRepaidKobo}, '
      'cash ${s.cashPaidKobo}, signatures '
      '${s.workerSignaturePng == null ? 'worker missing' : 'worker'} / '
      '${s.payerSignaturePng == null ? 'payer missing' : 'payer'}',
    );
  }
  out
    ..writeln()
    ..writeln('## Combined pay lines (${plan.payTotals.length})')
    ..writeln();
  for (final t in plan.payTotals) {
    out.writeln(
      '- ${t.totalDate} ${t.kind}: amount ${t.amountKobo}, cash ${t.cashKobo}',
    );
  }
  out
    ..writeln()
    ..writeln('## Left out (${plan.leftOut.length})')
    ..writeln();
  for (final line in plan.leftOut) {
    out.writeln('- $line');
  }
  return out.toString();
}
