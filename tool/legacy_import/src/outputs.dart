String _orphanCount(String table, String column, String parent, String biz) =>
    '(SELECT count(*) FROM public.$table c WHERE c.business_id = $biz '
    'AND c.$column IS NOT NULL AND NOT EXISTS '
    '(SELECT 1 FROM public.$parent p WHERE p.id = c.$column))';

/// Output 1: one transaction, safe to run twice.
String buildImportSql({
  required ImportPlan plan,
  required ImportConfig config,
}) {
  final out = StringBuffer();
  final biz = sqlText(plan.businessId);
  final authUids = config.accounts.map((a) => sqlText(a.authUid)).join(', ');
  final columns = _quantityColumns
      .map((c) => "('${c.$1}', '${c.$2}')")
      .join(', ');

  out
    ..writeln('-- Generated by tool/legacy_import. Contains real shop data.')
    ..writeln(
      '-- Do not commit. Run with: psql -v ON_ERROR_STOP=1 -f import.sql',
    )
    ..writeln()
    ..writeln('BEGIN;')
    ..writeln();

  if (config.hasPlaceholderAccounts) {
    out
      ..writeln('-- Placeholder accounts: this file is for review only.')
      ..writeln(
        "DO \$\$ BEGIN RAISE EXCEPTION 'import.sql was generated with "
        "placeholder accounts'; END \$\$;",
      )
      ..writeln();
  }

  out
    ..writeln('-- Guards: nothing below runs on a schema it would damage.')
    ..writeln('DO \$\$')
    ..writeln('BEGIN')
    ..writeln('  IF EXISTS (')
    ..writeln('    SELECT 1 FROM (VALUES $columns) AS q(t, c)')
    ..writeln('    LEFT JOIN information_schema.columns ic')
    ..writeln("      ON ic.table_schema = 'public' AND ic.table_name = q.t")
    ..writeln('     AND ic.column_name = q.c')
    ..writeln("    WHERE ic.data_type IS DISTINCT FROM 'double precision'")
    ..writeln('  ) THEN')
    ..writeln(
      "    RAISE EXCEPTION 'quantity columns are not double precision: "
      "apply the #627 migration first';",
    )
    ..writeln('  END IF;')
    ..writeln('  IF EXISTS (')
    ..writeln('    SELECT 1 FROM public.users')
    ..writeln('    WHERE auth_user_id IN ($authUids)')
    ..writeln('      AND business_id <> $biz')
    ..writeln('  ) THEN')
    ..writeln(
      "    RAISE EXCEPTION 'a login already belongs to another business';",
    )
    ..writeln('  END IF;')
    ..writeln('END \$\$;')
    ..writeln()
    ..writeln('-- Phase 1: triggers on. Premium is set on the business row, so')
    ..writeln('-- the plan-limit triggers on stores and staff see it first.');

  plan.businesses.writeInserts(out);
  out
    ..writeln()
    ..writeln('DO \$\$')
    ..writeln('BEGIN')
    ..writeln(
      '  IF NOT EXISTS (SELECT 1 FROM public.roles WHERE business_id = $biz) '
      'THEN',
    )
    ..writeln('    PERFORM public.seed_default_roles_for_business($biz);')
    ..writeln('  END IF;')
    ..writeln('END \$\$;')
    ..writeln();
  for (final table in plan.identityTables) {
    table.writeInserts(out);
  }

  out
    ..writeln()
    ..writeln('-- Phase 2: triggers off, so 30,000 rows send no broadcasts.')
    ..writeln('-- This also switches FK checks off; see the block below.')
    ..writeln('SET LOCAL session_replication_role = replica;')
    ..writeln();
  for (final table in plan.historyTables) {
    table.writeInserts(out);
  }

  out
    ..writeln()
    ..writeln('SET LOCAL session_replication_role = origin;')
    ..writeln()
    ..writeln('-- Foreign keys, checked by hand: any orphan aborts everything.')
    ..writeln('DO \$\$')
    ..writeln('BEGIN');
  for (final (table, column, parent) in _foreignKeys) {
    out
      ..writeln('  IF ${_orphanCount(table, column, parent, biz)} > 0 THEN')
      ..writeln("    RAISE EXCEPTION 'orphan rows in $table.$column';")
      ..writeln('  END IF;');
  }
  out
    ..writeln('END \$\$;')
    ..writeln()
    ..writeln('COMMIT;');
  return out.toString();
}

/// `(VALUES ...) AS e(k, v)`, or an empty relation of the same shape.
String _expected(Map<String, num> values) {
  if (values.isEmpty) {
    return '(SELECT NULL::text AS k, 0::numeric AS v WHERE false) e';
  }
  final rows = values.entries
      .map((e) => '(${sqlText(e.key)}, ${e.value}::numeric)')
      .join(', ');
  return '(VALUES $rows) AS e(k, v)';
}

/// How many keys differ between the expected figures and [actualSql], which
/// must select `k` (text) and `v` (numeric). A key on one side only counts.
String _mismatches(Map<String, num> expected, String actualSql) =>
    '(SELECT count(*) FROM ${_expected(expected)} '
    'FULL JOIN ($actualSql) AS a USING (k) '
    'WHERE coalesce(e.v, 0) <> coalesce(a.v, 0))';

class _Checks {
  final List<String> rows = [];

  void add(String name, num expected, String actualSql) {
    rows.add(
      'SELECT ${rows.length} AS ord, ${sqlText(name)} AS check_name, '
      '$expected::numeric AS expected, ($actualSql)::numeric AS actual',
    );
  }

  /// A check that lists no differences.
  void none(String name, String mismatchSql) => add(name, 0, mismatchSql);
}

/// Output 2: read-only. One row per check, plus an overall verdict.
String buildChecksSql({
  required ImportPlan plan,
  required ImportConfig config,
}) {
  final biz = sqlText(plan.businessId);
  final where = 'WHERE business_id = $biz';
  final cutover = sqlTime(plan.cutover);
  final checks = _Checks();

  final tables = [
    plan.businesses,
    ...plan.identityTables,
    ...plan.historyTables,
  ].where((table) => table.name != 'businesses' && table.name != 'profiles');
  for (final table in tables) {
    checks.add(
      'rows: ${table.name}',
      table.rows.length,
      'SELECT count(*) FROM public.${table.name} $where',
    );
  }

  checks
    ..add(
      'business is Premium with no end date, one price, owner set',
      1,
      'SELECT count(*) FROM public.businesses WHERE id = $biz '
          "AND subscription_status = 'active' "
          "AND subscription_plan = 'premium' AND current_period_end IS NULL "
          'AND sells_one_price AND onboarding_complete '
          'AND owner_id = ${sqlText(config.ownerAuthUid)}',
    )
    ..add(
      'hidden staff memberships',
      config.accounts.where((account) => account.hidden).length,
      'SELECT count(*) FROM public.user_businesses $where AND is_hidden',
    )
    ..add(
      'every account has a login',
      config.accounts.length,
      'SELECT count(*) FROM auth.users WHERE id::text IN '
          '(${config.accounts.map((a) => sqlText(a.authUid)).join(', ')})',
    )
    ..none(
      'each customer balance = -(old ledger sum)',
      _mismatches(
        plan.customerBalanceKobo,
        'SELECT customer_id::text AS k, sum(signed_amount_kobo)::numeric AS v '
        'FROM public.wallet_transactions $where AND reference_type NOT IN '
        "('crate_deposit', 'crate_deposit_refunded', "
        "'crate_deposit_forfeited') GROUP BY 1",
      ),
    )
    ..add(
      'all customers net',
      plan.customerBalanceKobo.values.fold<int>(0, (sum, v) => sum + v),
      'SELECT coalesce(sum(signed_amount_kobo), 0) '
          'FROM public.wallet_transactions $where AND reference_type NOT IN '
          "('crate_deposit', 'crate_deposit_refunded', "
          "'crate_deposit_forfeited')",
    )
    ..none(
      'each held deposit matches',
      _mismatches(
        plan.heldDepositKobo,
        'SELECT customer_id::text AS k, sum(signed_amount_kobo)::numeric AS v '
        'FROM public.wallet_transactions $where AND reference_type IN '
        "('crate_deposit', 'crate_deposit_refunded', "
        "'crate_deposit_forfeited') GROUP BY 1",
      ),
    )
    ..none(
      'each supplier balance = -(old ledger sum)',
      _mismatches(
        plan.supplierBalanceKobo,
        'SELECT supplier_id::text AS k, sum(signed_amount_kobo)::numeric AS v '
        'FROM public.supplier_ledger_entries $where GROUP BY 1',
      ),
    )
    ..add(
      'all suppliers net',
      plan.supplierBalanceKobo.values.fold<int>(0, (sum, v) => sum + v),
      'SELECT coalesce(sum(signed_amount_kobo), 0) '
          'FROM public.supplier_ledger_entries $where',
    )
    ..none(
      'stock per store per product',
      _mismatches(
        {
          for (final figure in plan.stock)
            '${figure.productId}|${figure.storeId}': figure.qty,
        },
        "SELECT product_id::text || '|' || store_id::text AS k, "
        'quantity::numeric AS v FROM public.inventory $where',
      ),
    )
    ..none(
      'live sales count per day',
      _mismatches({
        for (final d in plan.days.entries) d.key: d.value.sales,
      }, _perDay('count(*)', 'public.orders', 'created_at', biz)),
    )
    ..none(
      'takings per day',
      _mismatches({
        for (final d in plan.days.entries) d.key: d.value.takingsKobo,
      }, _perDay('sum(net_amount_kobo)', 'public.orders', 'created_at', biz)),
    )
    ..none(
      'cash received at the till per day',
      _mismatches(
        {
          for (final d in plan.days.entries)
            if (d.value.cashKobo != 0) d.key: d.value.cashKobo,
        },
        "SELECT to_char(pt.created_at AT TIME ZONE 'Africa/Lagos', "
        "'YYYY-MM-DD') AS k, sum(pt.amount_kobo)::numeric AS v "
        'FROM public.payment_transactions pt '
        'WHERE pt.business_id = $biz AND pt.order_id IS NOT NULL GROUP BY 1',
      ),
    )
    ..add(
      'cancelled sales',
      plan.cancelledSales,
      "SELECT count(*) FROM public.orders $where AND status = 'cancelled'",
    )
    ..add(
      'cancelled sales add no money',
      0,
      'SELECT coalesce(sum(pt.amount_kobo), 0) '
          'FROM public.payment_transactions pt '
          'JOIN public.orders o ON o.id = pt.order_id '
          "WHERE o.business_id = $biz AND o.status = 'cancelled'",
    )
    ..none(
      'crate balance per customer per company (ledger)',
      _mismatches(
        plan.crates,
        "SELECT customer_id::text || '|' || manufacturer_id::text AS k, "
        'sum(quantity_delta)::numeric AS v FROM public.crate_ledger $where '
        'AND customer_id IS NOT NULL GROUP BY 1',
      ),
    )
    ..none(
      'crate balance per customer per company (balance table)',
      _mismatches(
        plan.crates,
        "SELECT customer_id::text || '|' || manufacturer_id::text AS k, "
        'balance::numeric AS v FROM public.customer_crate_balances $where',
      ),
    )
    ..add(
      'past lines at zero cost (free goods only)',
      plan.zeroCostLines,
      'SELECT count(*) FROM public.order_items $where '
          'AND buying_price_kobo = 0',
    )
    ..none(
      'no sold line has a zero or negative cost',
      'SELECT count(*) FROM public.order_items $where '
          'AND buying_price_kobo <= 0 AND unit_price_kobo > 0',
    )
    ..none(
      'history layers hold exactly the units sold',
      'SELECT count(*) FROM ('
          'SELECT product_id, store_id, sum(qty) AS total FROM ('
          'SELECT oi.product_id, oi.store_id, oi.quantity AS qty '
          'FROM public.order_items oi JOIN public.orders o ON o.id = oi.order_id '
          "WHERE oi.business_id = $biz AND o.status = 'completed' "
          'UNION ALL SELECT product_id, store_id, -qty_original '
          'FROM public.cost_batches $where AND received_at < $cutover'
          ') m GROUP BY 1, 2 HAVING sum(qty) <> 0) d',
    )
    ..add(
      'history layers are fully drawn',
      0,
      'SELECT coalesce(sum(qty_remaining), 0) FROM public.cost_batches '
          '$where AND received_at < $cutover',
    )
    ..none(
      'opening layers equal stock on hand',
      _mismatches(
        {
          for (final figure in plan.stock)
            if (figure.qty > 0)
              '${figure.productId}|${figure.storeId}': figure.qty,
        },
        "SELECT product_id::text || '|' || store_id::text AS k, "
        'sum(qty_remaining)::numeric AS v FROM public.cost_batches $where '
        'GROUP BY 1',
      ),
    )
    ..none(
      'a FIFO replay changes no past line cost',
      'SELECT count(*) FROM ('
          'SELECT DISTINCT product_id, store_id FROM public.order_items $where'
          ') p CROSS JOIN LATERAL (SELECT public.fifo_assign('
          "(SELECT coalesce(jsonb_agg(jsonb_build_object('cost_kobo', "
          "cb.cost_kobo, 'qty', cb.qty_original) ORDER BY cb.received_at, cb.id"
          "), '[]'::jsonb) FROM public.cost_batches cb "
          'WHERE cb.business_id = $biz AND cb.product_id = p.product_id '
          'AND cb.store_id = p.store_id), '
          "(SELECT coalesce(jsonb_agg(jsonb_build_object('line_id', oi.id, "
          "'quantity', oi.quantity) ORDER BY o.created_at, o.id, oi.id), "
          "'[]'::jsonb) FROM public.order_items oi "
          'JOIN public.orders o ON o.id = oi.order_id '
          'WHERE oi.business_id = $biz AND oi.product_id = p.product_id '
          "AND oi.store_id = p.store_id AND o.status IN ('pending', "
          "'completed') AND o.van_trip_id IS NULL)) AS r) f "
          "CROSS JOIN LATERAL jsonb_array_elements(f.r -> 'lines') l "
          "JOIN public.order_items oi ON oi.id = (l ->> 'line_id')::uuid "
          'WHERE oi.buying_price_kobo IS DISTINCT FROM '
          "(l ->> 'cogs_per_unit_kobo')::bigint",
    );

  for (final (table, column, parent) in _foreignKeys) {
    checks.none(
      'no orphans: $table.$column',
      _orphanCount(table, column, parent, biz),
    );
  }

  final out = StringBuffer()
    ..writeln('-- Generated by tool/legacy_import. Contains real shop data.')
    ..writeln('-- Read-only: every row should say PASS.')
    ..writeln('BEGIN TRANSACTION READ ONLY;')
    ..writeln()
    ..writeln('WITH c AS (')
    ..writeln(checks.rows.join('\nUNION ALL\n'))
    ..writeln('), r AS (')
    ..writeln(
      "  SELECT ord, check_name, expected, actual, CASE WHEN expected = actual "
      "THEN 'PASS' ELSE 'FAIL' END AS result FROM c",
    )
    ..writeln(')')
    ..writeln('SELECT check_name, expected, actual, result FROM r')
    ..writeln('UNION ALL')
    ..writeln(
      "SELECT 'ALL CHECKS (failures)', 0, count(*) FILTER (WHERE result = "
      "'FAIL'), CASE WHEN count(*) FILTER (WHERE result = 'FAIL') = 0 THEN "
      "'PASS' ELSE 'FAIL' END FROM r;",
    )
    ..writeln()
    ..writeln('ROLLBACK;');
  return out.toString();
}

String _perDay(String measure, String table, String column, String biz) =>
    "SELECT to_char($column AT TIME ZONE 'Africa/Lagos', 'YYYY-MM-DD') AS k, "
    '$measure::numeric AS v FROM $table WHERE business_id = $biz '
    "AND status = 'completed' GROUP BY 1";

/// Output 3: the run report. Stays beside the export, because it has real
/// totals in it.
String buildReport({
  required ImportPlan plan,
  required ImportConfig config,
  required Map<String, int> manifestRows,
}) {
  String naira(int kobo) {
    final digits = (kobo.abs() ~/ 100).toString().replaceAllMapped(
      RegExp(r'\B(?=(\d{3})+$)'),
      (_) => ',',
    );
    final cents = (kobo.abs() % 100).toString().padLeft(2, '0');
    return '${kobo < 0 ? '-' : ''}N$digits.$cents';
  }

  final out = StringBuffer()
    ..writeln('# Legacy import report')
    ..writeln()
    ..writeln('Export taken: ${plan.cutover.toIso8601String()}')
    ..writeln('Business id: ${plan.businessId}')
    ..writeln();
  if (config.hasPlaceholderAccounts) {
    out
      ..writeln('**Placeholder accounts: import.sql refuses to run. Regenerate')
      ..writeln('with the real login ids before any dry run.**')
      ..writeln();
  }

  out
    ..writeln('## Rows')
    ..writeln()
    ..writeln('| Table | Rows |')
    ..writeln('|---|---:|');
  for (final table in [
    plan.businesses,
    ...plan.identityTables,
    ...plan.historyTables,
  ]) {
    out.writeln('| ${table.name} | ${table.rows.length} |');
  }

  out
    ..writeln()
    ..writeln('## Old rows read (all matched the manifest)')
    ..writeln()
    ..writeln('| Old table | Rows |')
    ..writeln('|---|---:|');
  manifestRows.forEach((table, rows) => out.writeln('| $table | $rows |'));

  final groups = plan.costGroups;
  final allLines = groups.values.fold<int>(0, (sum, g) => sum + g.lines);
  final takings = groups.values.fold<int>(0, (sum, g) => sum + g.takingsKobo);
  out
    ..writeln()
    ..writeln('## Live sale lines by cost group')
    ..writeln()
    ..writeln('| Group | Lines | Takings | Estimated cost | Profit |')
    ..writeln('|---|---:|---:|---:|---:|');
  for (final group in CostGroup.values) {
    final figures = groups[group]!;
    out.writeln(
      '| ${group.name.toUpperCase()} | ${figures.lines} '
      '| ${naira(figures.takingsKobo)} | ${naira(figures.costKobo)} '
      '| ${naira(figures.takingsKobo - figures.costKobo)} |',
    );
  }
  out
    ..writeln('| All | $allLines | ${naira(takings)} | | |')
    ..writeln()
    ..writeln('Lines left at cost 0 (free goods): ${plan.zeroCostLines}')
    ..writeln()
    ..writeln('## Money')
    ..writeln()
    ..writeln(
      '- Live sales: ${plan.days.values.fold<int>(0, (s, d) => s + d.sales)}; '
      'cancelled: ${plan.cancelledSales}',
    )
    ..writeln(
      '- Cash at the till: '
      '${naira(plan.days.values.fold<int>(0, (s, d) => s + d.cashKobo))}',
    )
    ..writeln(
      '- Customers owe: ${naira(-_owed(plan.customerBalanceKobo.values))} '
      '(${plan.customerBalanceKobo.values.where((v) => v < 0).length} '
      'customers); net ${naira(plan.customerBalanceKobo.values.fold<int>(0, (s, v) => s + v))}',
    )
    ..writeln(
      '- Owed to suppliers: ${naira(-_owed(plan.supplierBalanceKobo.values))} '
      '(${plan.supplierBalanceKobo.values.where((v) => v < 0).length} '
      'suppliers)',
    )
    ..writeln(
      '- Held deposits: '
      '${naira(plan.heldDepositKobo.values.fold<int>(0, (s, v) => s + v))}',
    )
    ..writeln(
      '- Crate balances: ${plan.crates.length}, totalling '
      '${plan.crates.values.fold<double>(0, (s, v) => s + v)} crates',
    )
    ..writeln()
    ..writeln('## Left out or changed')
    ..writeln();
  for (final note in plan.notes.toSet()) {
    out.writeln('- $note');
  }
  return out.toString();
}

int _owed(Iterable<int> balances) =>
    balances.where((v) => v < 0).fold<int>(0, (sum, v) => sum + v);
